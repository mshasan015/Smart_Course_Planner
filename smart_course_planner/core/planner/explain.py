"""
Explainer and Backup Section Finder.
Day 9 Smart extras:
1. Explains why no plan was found (identifies bottleneck courses and constraint conflicts).
2. Finds backup sections for each chosen section that fit the rest of the schedule.
"""

from typing import List, Dict, Tuple, Optional
from core.models import Course, Section, Schedule
from core.planner.preference import Preference
from core.planner.brute_force import BruteForcePlanner
from core.conflict import ConflictChecker


class Explainer:
    """
    Diagnoses infeasible preferences and computes backup recommendations.
    """

    def __init__(self, courses: List[Course]):
        self.courses = courses
        self.courses_dict = {c.code: c for c in courses}
        all_sections = [s for c in courses for s in c.sections]
        self.conflict_checker = ConflictChecker(all_sections)

    def explain_failure(self, preference: Preference) -> List[str]:
        """
        Diagnoses why no plan could be generated by:
        1. Checking if any wanted course has 0 valid sections due to hard constraints (e.g. 'No class before 10 AM').
        2. Removing one course at a time to determine which specific course combination causes clashes.
        """
        reasons: List[str] = []

        if not preference.wanted_courses:
            return ["No courses were selected in preferences."]

        # Check 1: Empty courses or missing courses
        for code in preference.wanted_courses:
            course = self.courses_dict.get(code)
            if not course:
                reasons.append(f"Course '{code}' was not found in the loaded routine.")
                continue

            # Check if all sections are dropped
            active_secs = [s for s in course.sections if not s.dropped]
            if not active_secs:
                reasons.append(f"All sections of course '{code}' are marked as Dropped.")
                continue

            # Check if early class constraint eliminates all sections
            if preference.no_early_class_hard:
                non_early_secs = [
                    s for s in active_secs
                    if not any(m.start < preference.no_class_before_minutes for m in s.meetings)
                ]
                if not non_early_secs:
                    reasons.append(
                        f"Hard rule 'No class before 10:00 AM' eliminates all active sections of {code}."
                    )

        if reasons:
            return reasons

        # Check 2: Try removing one course at a time to isolate bottleneck
        planner = BruteForcePlanner(self.courses)

        problematic_courses = []
        for code in preference.wanted_courses:
            reduced_courses = [c for c in preference.wanted_courses if c != code]
            if not reduced_courses:
                continue

            test_pref = Preference(
                wanted_courses=reduced_courses,
                liked_faculty=preference.liked_faculty,
                avoided_faculty=preference.avoided_faculty,
                no_class_before_minutes=preference.no_class_before_minutes,
                no_early_class_hard=preference.no_early_class_hard,
                no_early_class_soft=preference.no_early_class_soft,
                priority=preference.priority,
            )

            plans = planner.plan(test_pref, top_k=1)
            if plans:
                # Removing 'code' allowed finding a solution -> 'code' is in conflict
                problematic_courses.append(code)

        if problematic_courses:
            if len(problematic_courses) == len(preference.wanted_courses):
                reasons.append(
                    f"Every selected course has unavoidable timing conflicts with the others: {', '.join(problematic_courses)}."
                )
            else:
                reasons.append(
                    f"Conflicting courses identified: Removing {', '.join(problematic_courses)} creates a clash-free schedule."
                )
        else:
            reasons.append(
                "Severe time conflicts exist across multiple course combinations simultaneously. Consider relaxing timing rules or selecting alternate courses."
            )

        return reasons

    def find_backup_sections(
        self, schedule: Schedule, preference: Optional[Preference] = None
    ) -> Dict[str, List[Tuple[Section, str]]]:
        """
        For each chosen section in the schedule, finds other valid sections of the same course
        that fit seamlessly into the rest of the schedule (without creating new clashes).
        Returns a dictionary mapping 'COURSE_CODE' -> list of (backup_section, reason).
        """
        backups_map: Dict[str, List[Tuple[Section, str]]] = {}

        for chosen_sec in schedule.sections:
            course = self.courses_dict.get(chosen_sec.course_code)
            if not course:
                continue

            # Remaining sections in schedule if chosen_sec is removed
            rest_of_schedule = [s for s in schedule.sections if s != chosen_sec]

            valid_backups: List[Tuple[Section, str]] = []

            for candidate in course.sections:
                if candidate.section_name == chosen_sec.section_name:
                    continue  # Already chosen
                if candidate.dropped:
                    continue

                # Check early class rule if hard
                if preference and preference.no_early_class_hard:
                    if any(m.start < preference.no_class_before_minutes for m in candidate.meetings):
                        continue

                # Check if candidate clashes with any section in rest_of_schedule
                has_clash, clashing_sec = self.conflict_checker.does_clash_with_selection(
                    candidate, rest_of_schedule
                )

                if not has_clash:
                    seats = candidate.seats_left()
                    faculty_str = ", ".join(candidate.teachers)
                    note = f"Seats left: {seats} | Faculty: {faculty_str}"
                    valid_backups.append((candidate, note))

            backups_map[chosen_sec.course_code] = valid_backups

        return backups_map
